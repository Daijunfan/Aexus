/** Built before committing a newly hired card, with the target identity, never the creator. */
export function employeeGuideFiles(card:StoredSession,store:Store){
  const snapshot={...store,sessions:[...store.sessions.filter(c=>c.id!==card.id),card]}
  const context={principal:{kind:'agent' as const,employeeId:card.id},requestId:'workspace-documentation'}
  const cli=employeeCli(card,snapshot),api=apiDocumentation(context,snapshot).markdown
  return {api:cli==='agents'?api:api.replace(/\bagents(?=\s)/g,cli),permissions:permissionDocumentation(context,snapshot),instructions:employeeInstructions(card,snapshot)}
}

/** Idempotent, role-aware preparation. Never moves files or changes engine permissions. */
export function ensureEmployeeBootstrap(card:StoredSession,store=readStore()){
  const settings=employeeSettings(store,card),root=employeeRoot(store,card)
  if(!root)throw new Error('Employee Team has no working directory')
  const guide=employeeGuideFiles(card,store)
  if(settings.mode==='cloud')return {mode:settings.mode,workspace:card.cwd,teamRoot:root,plugins:[],instructions:guide.instructions}
  const cwd=fs.realpathSync(card.cwd),directory=path.join(cwd,'.agents-company'),folder=path.join(directory,'employees',card.id)
  // Plugin and company sections have different markers and compose in either order.
  if(settings.mode==='work')provisionWorkspace(cwd,settings,root)
  else instructions(cwd,'') // Remove the obsolete directory-based full-Manager block only.
  const cli=path.join(applicationRoot(),'bin/agents')
  writeWindowsCompanyLauncher(cwd,directory,cli,safeWrite)
  safeWrite(cwd,path.join(directory,'bin','agents'),`#!/bin/sh
# Generated by Agents Company; uses only the identity assigned to the caller.
if [ -z "$AGENTS_COMPANY_TOKEN_FILE" ] && [ -z "$AGENTS_COMPANY_TOKEN" ]; then
  echo 'Agent identity missing; reopen this employee in Agents Company.' >&2; exit 2
fi
exec env ELECTRON_RUN_AS_NODE=1 ${quote(process.execPath)} ${quote(cli)} "$@"
`,true)
  safeWrite(cwd,path.join(folder,'API.md'),guide.api+'\n')
  for(const name of ['AGENTS.md','CLAUDE.md'])safeWrite(cwd,path.join(folder,name),guide.instructions+'\n')
  safeWrite(cwd,path.join(folder,'PERMISSIONS.md'),guide.permissions)
  safeWrite(cwd,path.join(folder,'bootstrap.json'),JSON.stringify({version:BOOTSTRAP_VERSION,employeeId:card.id,managementRole:card.managementRole??'employee',globalManager:hasGlobalRole(store.access,card)},null,2)+'\n')
  const entry='# Agents Company API entry\n\nRun `agents auth whoami --json` to identify this process, then read `.agents-company/employees/<employeeId>/API.md` and `PERMISSIONS.md`, or run `agents api docs`. Shared folders do not share authority.\n'
  safeWrite(cwd,path.join(directory,'API.md'),entry)
  // Neutralize old full-global handbooks without deleting user instructions or history.
  if(isSupervisor(card.managementRole)||fs.existsSync(path.join(directory,'manager','API.md')))safeWrite(cwd,path.join(directory,'manager','API.md'),entry)
  instructions(cwd,`${COMPANY_BEGIN}
## Agents Company CLI

This workspace belongs to registered Agents Company employees. Read the role-specific
\`.agents-company/employees/<employeeId>/API.md\` and \`PERMISSIONS.md\` named in your launch instructions.
Run \`agents auth whoami --json\` and \`agents api docs\` first. The fallback launcher is \`./.agents-company/bin/agents\`.
Managers create registered employees with \`agents card create\`, then control them with \`session.*\` and \`schedule.*\`.
Coding Agent native subagents / Agent / Task are not company employees. Do not use them as a substitute.
Credentials and permissions come from the running process, never the directory name or this file.
${COMPANY_END}`,COMPANY_BEGIN,COMPANY_END)
  return {mode:settings.mode,workspace:cwd,teamRoot:root,plugins:settings.mode==='work'?[settings.pluginId!]:[],instructions:guide.instructions}
}

/** Compatibility helper for callers preparing a folder before there is an employee record. */
export function provisionEmployee(cwd:string,root:string,settings:TeamSettings){
  if(settings.mode==='cloud')return {mode:settings.mode,workspace:cwd,teamRoot:root,plugins:[]}
  const store=readStore(),cards=store.sessions.filter(c=>c.cwd===cwd&&!c.deleting)
  if(cards.length){for(const card of cards)ensureEmployeeBootstrap(card,store);return {mode:settings.mode,workspace:cwd,teamRoot:root,plugins:[]}}
  return settings.mode==='work'?provisionWorkspace(cwd,settings,root):{mode:settings.mode,workspace:cwd,teamRoot:root,plugins:[]}
}

