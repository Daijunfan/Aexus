function employeeCli(card:StoredSession,store:Store){
  const config=employeeSettings(store,card)
  if(config.mode!=='cloud'||card.kind==='cloud-native-worker')return 'agents'
  const windows=config.remote?.os==='windows',paths=windows?path.win32:path.posix
  const file=paths.join(card.cwd,'.agents-company','employees',card.id,'bin',windows?'agents.cmd':'agents')
  return windows?`& '${file.replaceAll("'","''")}'`:quote(file)
}
