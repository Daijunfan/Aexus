window.runWorkspaceModeChecks=async function(){
 const checks=[],issues=[];
 window.addEventListener('error',event=>issues.push(event.message));
 window.addEventListener('unhandledrejection',event=>issues.push(String(event.reason)));
 const check=(name,good)=>checks.push({name,passed:!!good});
 const wait=async(fn,ms=10000)=>{const until=Date.now()+ms;do{if(await fn())return true;await new Promise(r=>setTimeout(r,65))}while(Date.now()<until);return false};
 const rpc=async(method,params={})=>{
  const response=await fetch('./rpc',{method:'POST',headers:{'content-type':'application/json'},body:JSON.stringify({jsonrpc:'2.0',id:Date.now(),method,params})}).then(v=>v.json());
  if(response.error)throw Error(response.error.message);return response.result;
 };
 const q=selector=>document.querySelector(selector);
 check('Application loads with four existing top-level workspaces',await wait(()=>!q('#add')?.disabled));
 q('#agent-board-mode').click();
 check('Agent workspace opens the existing Company-equivalent host board',await wait(()=>!!q('.agent-hub-nav')&&!!q('.agent-grid')));
 check('Agent workspace exposes Aexus-inspired Company, Messages and Plan tabs',q('.agent-hub-nav').querySelectorAll('[data-hub]').length===3);
 q('[data-hub="messages"]').click();
 check('Messages mounts independently without launching any Agent',await wait(()=>!!q('.collab-messages .collab-group-list')));
 q('.collab-new-group').click();
 check('Native group editor appears',await wait(()=>!!q('.collab-group-dialog[open]')));
 q('.collab-group-dialog [name=name]').value='研究讨论组';
 q('.collab-group-dialog [name=description]').value='Native discussions without model prompts';
 q('.collab-group-dialog form').dispatchEvent(new Event('submit',{bubbles:true,cancelable:true}));
 check('Group is saved by Core RPC and listed in Messages',await wait(async()=>{
  const groups=await rpc('messages.list');return groups.length===1&&groups[0].name==='研究讨论组'&&!!q('.collab-group-row.active')
 }));
 const group=(await rpc('messages.list'))[0];
 check('Native group name remains verbatim across English localization',q('.collab-group-row strong')?.textContent==='研究讨论组');
 const composer=q('.collab-composer [name=text]');composer.value='Check remote agent performance';
 composer.dispatchEvent(new Event('input',{bubbles:true}));
 q('.collab-composer').dispatchEvent(new Event('submit',{bubbles:true,cancelable:true}));
 check('Message composer persists an out-of-band message',await wait(async()=>
  (await rpc('messages.history',{id:group.id})).messages.length===1&&q('.collab-bubble p')?.textContent==='Check remote agent performance'
 ));
 check('No native Agent turn is generated by a group message',(await rpc('hosts.agent-list')).length===0);
 q('.collab-bubble [data-plan]').click();
 check('Plan this opens Plan with the original message text prefilled',await wait(()=>!!q('.collab-plan-dialog[open]')&&q('.collab-plan-dialog [name=text]')?.value==='Check remote agent performance'));
 const dialog=q('.collab-plan-dialog'),form=dialog.querySelector('form');
 form.elements.name.value='Reminder for discussion';
 form.elements.type.value='notice';form.elements.kind.value='once';form.elements.at.value='2032-01-01T12:00';
 form.elements.enabled.checked=false;
 form.dispatchEvent(new Event('submit',{bubbles:true,cancelable:true}));
 check('Plan creates a paused task and never submits to a model',await wait(async()=>
  (await rpc('plan.list')).length===1&&!q('.collab-plan-dialog[open]')
 ));
 const task=(await rpc('plan.list'))[0];
 check('Plan task retains out-of-band group linkage',task.action.type==='notice'&&task.action.groupId===group.id&&task.enabled===false);
 q('[data-layout="calendar"]').click();
 check('Aexus-style Calendar projection renders independently of task execution',!!q('.collab-calendar-grid')&&q('.collab-calendar-grid').children.length>30);
 q('[data-layout="timeline"]').click();
 check('Timeline presents scheduled task with its saved identity',q('.collab-timeline-row .collab-task-card h3')?.textContent==='Reminder for discussion');
 q('[data-layout="board"]').click();
 await wait(()=>!!q(`[data-run="${task.id}"]`));
 const run=q(`[data-run="${task.id}"]`);run.click();
 check('Run now requires an explicit second confirmation before execution',q(`[data-run="${task.id}"]`)?.textContent==='Confirm run'&&(await rpc('plan.history',{id:task.id})).length===0);
 q(`[data-run="${task.id}"]`).click();
 check('Manual Plan reminder creates a true execution record and group publication',await wait(async()=>
  (await rpc('plan.history',{id:task.id})).length===1&&(await rpc('messages.history',{id:group.id})).messages.length===2
 ));
 check('Reminder execution never starts a model session',(await rpc('hosts.agent-list')).length===0);
 q('[data-hub="messages"]').click();
 check('Plan publication appears in the shared group history',await wait(()=>q('.collab-messages-list').textContent.includes('Reminder for discussion')||q('.collab-messages-list').textContent.includes('Check remote agent performance')));
 check('Selected Agent workspace tab is stored with existing workbench settings',(await rpc('hosts.workspace')).agentBoard.hubTab==='messages');
 q('[data-hub="board"]').click();
 check('Returning to Agent Board does not drop the pre-existing board',await wait(()=>!!q('.agent-grid')&&!!q('#agent-columns')));
 check('No JS errors or unhandled rejections',issues.length===0);
 return {checks,passed:checks.every(c=>c.passed),issues};
};
