const {test,after}=require('node:test'),assert=require('node:assert/strict');
const fs=require('node:fs'),os=require('node:os'),path=require('node:path');
const root=fs.mkdtempSync(path.join(os.tmpdir(),'cloudhosts-plan-integrity-'));
process.env.CLOUD_HOSTS_HOME=root;
const agents=require('../src/agent-sessions.cjs');
const backup={sessions:agents.sessions,send:agents.send,read:agents.read,interrupt:agents.interrupt,activate:agents.activate};
const role={id:'agent-77',name:'Coder',engine:'codex',transport:'native',threadId:'thread-77',targetHostId:'local',engineHostId:'local',cwd:root,running:true,busy:false};
let sendCount=0,interruptCount=0,busyTurn='turn-77';
agents.sessions=()=>[structuredClone(role)];
agents.send=async()=>{sendCount++;return {accepted:true,turnId:busyTurn}};
agents.read=()=>({busy:true,turnId:busyTurn});
agents.interrupt=async()=>{interruptCount++;return {interrupted:true}};
agents.activate=async()=>role;
const plan=require('../src/plan-scheduler.cjs'),journal=require('../src/session-journal.cjs');
after(async()=>{await plan.stop();Object.assign(agents,backup);fs.rmSync(root,{recursive:true,force:true})});
test('Plan retry is idempotent and a note edit preserves occurrences and next run',()=>{
 const spec={kind:'interval',everySeconds:3600},action={type:'agent',mode:'resume',agentId:role.id,text:'Check logs'};
 const args={name:'Hourly audit',action,rule:spec,notes:'One',enabled:true,clientRequestId:'request-hourly-1'};
 const created=plan.create(args),again=plan.create(args);
 assert.equal(created.id,again.id);
 assert.throws(()=>plan.create({...args,name:'Other'}),/reused/);
 const newer=plan.update({id:created.id,patch:{notes:'Updated'}});
 assert.equal(newer.notes,'Updated');
 assert.equal(newer.nextAt,created.nextAt);
 assert.equal(newer.occurrences,created.occurrences);
});
test('submitted native run holds plan edits/archives and exact run cancel only',async()=>{
 const task=plan.create({name:'Active',action:{type:'agent',mode:'resume',agentId:role.id,text:'Execute'},rule:{kind:'once',at:new Date(Date.now()+70000).toISOString()}});
 plan.start();
 const run=await plan.run({id:task.id});
 assert.equal(run.status,'submitted');
 assert.equal(sendCount,1);
 assert.throws(()=>plan.update({id:task.id,patch:{notes:'Changed mid-turn'}}),/active/);
 assert.throws(()=>plan.archive({id:task.id}),/active/);
 await assert.rejects(()=>plan.run({id:task.id}),/active/);
 busyTurn='different-native-turn';
 await assert.rejects(()=>plan.cancel({runId:run.id}),/mismatch/);
 assert.equal(interruptCount,0);
 busyTurn=run.turnId;
 const cancelled=await plan.cancel({runId:run.id});
 assert.equal(cancelled.cancelRequestedAt!==undefined,true);
 assert.equal(interruptCount,1);
 await plan.cancel({runId:run.id});
 assert.equal(interruptCount,1);
 journal.observe(role,{method:'turn/completed',params:{threadId:role.threadId,turn:{id:run.turnId,status:'interrupted'}}});
 assert.equal(plan.history({id:task.id})[0].status,'interrupted');
 assert.equal(plan.update({id:task.id,patch:{notes:'Now safe'}}).notes,'Now safe');
 assert.equal(plan.archive({id:task.id}).archived,true);
});
test('calendar projects multiple recurrent dates and actual runs, analytics uses full history',()=>{
 const now=new Date(),year=now.getUTCFullYear()+1;
 const start=new Date(Date.UTC(year,0,1)),end=new Date(Date.UTC(year,1,1));
 const rule={kind:'weekly',days:[1,2,3,4,5],time:'09:00',timezone:'Asia/Tokyo'};
 const job=plan.create({name:'Weekdays',action:{type:'notice',text:'Heads up'},rule,enabled:true});
 const calendar=plan.calendar({start:start.toISOString(),end:end.toISOString()});
 assert.ok(calendar.occurrences.filter(row=>row.jobId===job.id).length>10);
 assert.ok(calendar.occurrences.every(row=>Date.parse(row.scheduledAt)>=start.valueOf()&&Date.parse(row.scheduledAt)<end.valueOf()));
 assert.ok(plan.analytics().plans>=2);
 assert.equal(plan.query({search:'Weekdays'}).rows[0].id,job.id);
 assert.deepEqual(plan.timeline({start:start.toISOString(),end:end.toISOString()}).occurrences,calendar.occurrences);
});
