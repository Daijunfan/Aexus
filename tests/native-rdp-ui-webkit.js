window.runNativeRdpUiChecks=async function(){
  const checks=[],test=(name,pass)=>checks.push({name,exact:!!pass});
  Object.defineProperty(navigator,'userAgent',{configurable:true,value:'Windows NT 10.0; Win64; x64'});
  const sent=[];
  window.chrome={webview:{postMessage:value=>sent.push(value)}};
  const host={id:'abcddcba-4444-4444-4444-a0a0a0a0a0a0',name:'Remote Desktop Fixture',os:'windows',desktop:{protocol:'rdp',address:'127.0.0.1',port:3389,viaHostId:'abcddcba-4444-4444-4444-a0a0a0a0a0a0'}};
  const sessionId='cccccccc-1111-4444-8888-eeeeeeeeeeee';
  const calls=[],messages=[];
  const rpc=async(method,params)=>{
    calls.push({method,params});
    if(method==='hosts.desktop-list')return [];
    if(method==='hosts.desktop-open')return {id:sessionId,hostId:host.id,protocol:'rdp',state:'ready',port:58912,address:'127.0.0.1',profile:'full address:s:127.0.0.1:58912'};
    if(method==='hosts.desktop-close')return {closed:true};
    if(method==='hosts.desktop-launch')return {launched:true};
    throw Error('unexpected '+method);
  };
  const root=document.querySelector('#root');
  let cleanup=window.__desktopPane(root,host,rpc,(text,type)=>messages.push({text,type}),()=>{},()=>{throw Error('RDP must not load the macOS client')});
  test('Windows RDP shows native desktop setup',!!root.querySelector('#desktop-connect'));
  root.querySelector('#desktop-connect').click();
  for(let i=0;i<12&&!root.querySelector('#desktop-launch');i++)await new Promise(r=>setTimeout(r,20));
  test('Native connection uses current desktop-open RPC',calls.some(x=>x.method==='hosts.desktop-open')&&!!root.querySelector('#desktop-launch'));
  const launch=root.querySelector('#desktop-launch');
  test('Windows RDP offers in-app native launch',launch?.textContent==='在云主机中打开 RDP');
  launch?.click();
  test('Bridge receives host GUID and validated session ID only',sent.length===1&&sent[0].type==='rdp-open'&&sent[0].id===host.id&&sent[0].session===sessionId);
  window.dispatchEvent(new CustomEvent('rdp-native-result',{detail:{state:'opened',session:sessionId}}));
  test('Native open event updates desktop status',root.querySelector('#desktop-status')?.textContent.includes('已打开'));
  window.dispatchEvent(new CustomEvent('rdp-native-result',{detail:{state:'error',session:sessionId,error:'ActiveX unavailable'}}));
  test('Native failure is visible with a system-client fallback',messages.at(-1)?.text.includes('ActiveX')&&root.querySelector('#desktop-download')!==null);
  test('Native error exposes a direct system launcher',root.querySelector('#desktop-launch')?.textContent==='使用系统远程桌面');
  root.querySelector('#desktop-launch')?.click();
  await Promise.resolve();
  test('System RDP fallback calls platform launcher',calls.some(x=>x.method==='hosts.desktop-launch'&&x.params?.session===sessionId));
  window.dispatchEvent(new CustomEvent('rdp-native-result',{detail:{state:'closed',session:sessionId}}));
  test('Native close event releases desktop UI state',root.querySelector('#desktop-connect')?.disabled===false&&root.querySelector('#desktop-disconnect')?.disabled===true);
  cleanup();
  return {checks,passed:checks.every(x=>x.exact)};
};
