 await expect.poll(()=>globe.evaluate(canvas=>canvas.width)).toBeGreaterThan(200)
 await page.locator('.guardian-scroll').evaluate(element=>element.scrollTop=0)
 report.firstScreen=await page.evaluate(()=>({height:innerHeight,panels:['.guardian-memory-panel','.guardian-disk-panel','.guardian-security-panel','.guardian-map-status'].map(selector=>{const box=document.querySelector(selector).getBoundingClientRect();return {selector,top:box.top,bottom:box.bottom}})}))
 report.firstScreenFits=report.firstScreen.panels.every(panel=>panel.top>=0&&panel.bottom<=report.firstScreen.height+1)
 await screenshot('aexus-guardian-overview')
 await app.evaluate(({app})=>app.getAppMetrics())
 await page.waitForTimeout(2000)
 report.resourceSample=await app.evaluate(({app})=>app.getAppMetrics().map(process=>({type:process.type,cpuPercent:process.cpu.percentCPUUsage,memoryKiB:process.memory.workingSetSize})))
 await page.getByRole('button',{name:'暂停地球旋转',exact:true}).click()
 await expect(page.getByRole('button',{name:'启动地球旋转',exact:true})).toHaveAttribute('aria-pressed','false')
 const before=await globe.evaluate(canvas=>canvas.toDataURL())
 await page.mouse.move(size.x+size.width*.5,size.y+size.height*.5);await page.mouse.down()
 await page.mouse.move(size.x+size.width*.7,size.y+size.height*.58,{steps:12});await page.mouse.up()
 await expect.poll(()=>globe.evaluate(canvas=>canvas.toDataURL())).not.toBe(before)
 const rotated=await globe.evaluate(canvas=>canvas.toDataURL())
 await page.mouse.wheel(0,-180)
 await expect(page.locator('.guardian-globe-controls')).toContainText('118%')
 await expect.poll(()=>globe.evaluate(canvas=>canvas.toDataURL())).not.toBe(rotated)
 pass('The rendered globe responds to pointer rotation and wheel input')

 await app.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows()[0].setSize(720,900))
 await expect(page.locator('.guardian-view')).toBeVisible()
 await expect.poll(()=>page.locator('.guardian-view').evaluate(element=>element.scrollWidth-element.clientWidth)).toBeLessThanOrEqual(1)
 assert.ok(await page.locator('.app-view-button').evaluateAll(elements=>elements.every(element=>{const box=element.getBoundingClientRect();return box.left>=0&&box.right<=innerWidth})))
 report.compactNavigation=await page.locator('.app-view-button').evaluateAll(elements=>elements.map(element=>{const label=[...element.children].find(child=>child.tagName==='SPAN'&&child.textContent.trim());return {label:label?.textContent.trim(),width:label?.clientWidth,contentWidth:label?.scrollWidth}}))
 assert.ok(report.compactNavigation.every(label=>label.width>=label.contentWidth),'compact navigation labels must be fully visible: '+JSON.stringify(report.compactNavigation))
 await screenshot('aexus-guardian-compact')
 await app.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows()[0].setSize(1512,982))
 await page.getByRole('button',{name:'Messages',exact:true}).click();await expect(page.locator('.channel-conversation')).toContainText('Security observations')
 await page.getByRole('button',{name:'Guardian',exact:true}).click();await expect(page.locator('.guardian-view')).toBeVisible()
 pass('Compact 720 px layout has no horizontal overflow and navigation preserves the active channel')

 // Exercise the visible-page polling path without foregrounding the disposable native window.
 await page.evaluate(()=>Object.defineProperty(document,'hidden',{configurable:true,get:()=>false}))
 const sampleTime=page.locator('.guardian-sample-time b'),beforePolling=await sampleTime.innerText()
 await expect.poll(()=>sampleTime.innerText(),{timeout:12000,intervals:[500]}).not.toBe(beforePolling)
 await page.getByRole('button',{name:'暂停实时采样',exact:true}).click()
 await expect(page.getByRole('button',{name:'恢复实时采样',exact:true})).toHaveAttribute('aria-pressed','true')
 const pausedAt=await sampleTime.innerText();await page.waitForTimeout(3500);assert.equal(await sampleTime.innerText(),pausedAt)
 const search=page.getByRole('textbox',{name:'搜索 Guardian 详情',exact:true})
 await search.fill('guardian-no-match-acceptance')
