 await page.locator(`[data-channel="${channel.id}"]`).click();await expect(page.locator('.channel-conversation')).toContainText('Security observations')
 await screenshot('aexus-messages-restored')
 await page.getByRole('button',{name:'Plan',exact:true}).click();await expect(page.locator('.plan-view')).toBeVisible()
 await page.getByRole('button',{name:'Company Views',exact:true}).click();await expect(page.locator('.infinite-canvas')).toBeVisible()
 pass('Restored channels and group conversations coexist with Company and Plan')

 const idleCount=(await call('session.list',{live:true})).length
 await page.getByRole('button',{name:'Guardian',exact:true}).click()
 await expect(page.locator('.guardian-view')).toBeVisible()
 const settings=await call('guardian.settings-get')
 assert.equal(settings.geoLookupEnabled,false);assert.equal(settings.home,null)
 await page.getByTestId('guardian-location-settings').click()
 const permissions=page.getByRole('dialog',{name:'让连接有迹可循',exact:true})
 await expect(permissions).toBeVisible();await expect(permissions).toContainText('ipwho.is')
 await expect(page.getByTestId('guardian-geo-consent')).not.toBeChecked()
 await page.getByTestId('guardian-geo-consent').check()
 await permissions.getByRole('button',{name:'取消',exact:true}).click()
 assert.equal((await call('guardian.settings-get')).geoLookupEnabled,false,'cancelled consent never enables external lookups')
 await expect(page.getByTestId('guardian-memory')).toBeVisible();await expect(page.getByTestId('guardian-disk')).toBeVisible()
 await expect(page.locator('.guardian-view')).toContainText('连接 ≠ 攻击')
 const first=await call('guardian.snapshot')
 assert.equal(first.host.platform,os.platform());assert.equal(first.host.arch,os.arch())
 assert.equal(first.memory.totalBytes,os.totalmem(),'memory total comes from the actual Core host')
 assert.ok(first.memory.usedBytes>0&&first.memory.usedBytes<=first.memory.totalBytes)
 assert.ok(first.disk?.totalBytes>0&&first.disk.availableBytes>=0&&first.disk.usedPercent>=0&&first.disk.usedPercent<=100)
 assert.ok(first.processes.length>0);assert.ok(first.processes.every(process=>Number.isInteger(process.pid)&&process.pid>0))
 assert.ok(first.network.interfaces.length>0);assert.equal(first.geo.enabled,false);assert.equal(first.geo.status,'disabled')
 assert.ok(first.network.connections.every(connection=>connection.location===null),'unapproved peers must not receive invented locations')
 assert.ok(first.network.connections.every(connection=>['inbound','unknown'].includes(connection.direction)),'unknown direction is retained')
 assert.deepEqual(first.security.map(check=>check.id).sort(),['filevault','firewall','sip'])
 await expect.poll(async()=>(await call('guardian.snapshot')).sampledAt,{timeout:15000,intervals:[1000]}).toBeGreaterThan(first.sampledAt)
 const next=await call('guardian.snapshot');assert.ok(next.history.length>=2)
 assert.ok(next.cpu.usagePercent===null||next.cpu.usagePercent>=0&&next.cpu.usagePercent<=100)
 report.telemetry={physicalMemoryBytes:next.memory.totalBytes,diskBytes:next.disk.totalBytes,processCount:next.processes.length,interfaceCount:next.network.interfaces.length,connectionCount:next.network.connections.length,historyPoints:next.history.length,issues:next.issues}
 await page.getByRole('button',{name:'立即刷新 Guardian',exact:true}).click()
 await expect(page.locator('.guardian-metric').first().locator('strong')).not.toHaveText('—')
 pass('Live Mac memory, disk, processes, interfaces, TCP observations and repeated samples are genuine')

 const globe=page.locator('.guardian-view canvas').first();await expect(globe).toBeVisible()
