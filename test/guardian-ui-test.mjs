 assert.deepEqual((await call('view.list')).views.map(view=>view.id),['company','messages','plan','guardian'])
 await expect(page.locator('.app-view-button')).toHaveCount(4)
 await expect(page.locator('.engine-library')).toHaveCount(0)
 pass('Company, Messages, Plan and Guardian are direct top-level views')

 await call('group.add',{name:'Guardian acceptance'})
 const employee=await call('card.create',{title:'Local fixture operator',group:'Guardian acceptance',engine:'codex',model:'gpt-6-luna',avatar:'byte'})
 await expect.poll(async()=>(await call('session.status',{employee:employee.id}))[0]?.initialization?.status).toBe('ready')
 const group=await call('chat.create',{name:'Security operations room',members:[employee.id]})
 const channel=await call('channel.create',{name:'Security observations',engine:{kind:'external',location:'local',name:'Acceptance fixture'}})
 await page.getByRole('button',{name:'Messages',exact:true}).click()
 await expect(page.locator(`[data-chat="${group.id}"]`)).toBeVisible()
 await expect(page.locator(`[data-channel="${channel.id}"]`)).toBeVisible()
