 report.defaultThemes=Object.fromEntries(Object.entries((await call('settings.get')).viewAppearance).map(([view,appearance])=>[view,appearance.theme]))
 assert.deepEqual(report.defaultThemes,{company:'white',messages:'white',plan:'white',guardian:'white'})
