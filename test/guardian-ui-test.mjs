const root=path.resolve(import.meta.dirname,'..'),require=createRequire(import.meta.url)
const temp=fs.realpathSync(fs.mkdtempSync(path.join(os.tmpdir(),'aexus-guardian-ui-')))
const control=path.join(temp,'fixture'),output=process.env.GUARDIAN_TEST_OUTPUT||path.join(root,'artifacts/guardian')
