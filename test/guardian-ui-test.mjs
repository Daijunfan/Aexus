 assert.ok((await connectionRows.allTextContents()).every(text=>text.toLowerCase().includes(processName.toLowerCase())))
 await page.getByRole('button',{name:'清除搜索',exact:true}).click()
 await page.getByRole('tab',{name:/^进程/}).click()
 await page.getByRole('button',{name:'按内存排序 ↓',exact:true}).click()
