 page.on('console',message=>{if(message.type()==='error')consoleErrors.push(message.text())})
 page.on('request',request=>{if(/^https?:/.test(request.url()))externalRequests.push(request.url())})
 await app.evaluate(()=>{globalThis.guardianFetchUrls=[];const original=globalThis.fetch;globalThis.fetch=(input,options)=>{globalThis.guardianFetchUrls.push(String(typeof input==='string'?input:input.url??input));return original(input,options)}})
 await expect(page.locator('.infinite-canvas')).toBeVisible()
