"use strict";
const assert = require('node:assert/strict');
exports.exercise = async ({api,deny,get,change,setId,pdf,a,b,excerptId}) => {
  const notes = await api('study.document.ensure',{id:pdf.id,activate:false});
  assert.equal((await api('study.document.ensure',{id:pdf.id,activate:false})).id,notes.id);
  await change('study.navigation.set',{mode:'both'});
  const jump=await api('study.card.activate',{setId,cardId:excerptId});
  assert.equal(jump.source.documentId,pdf.id);assert.equal(jump.source.locator.page,1);
  assert.equal(jump.source.locator.pageOffset,.1);
  let s=await change('study.annotation.update',{cardId:excerptId,visible:false,style:'underline'});
  assert.equal(s.cards.find(c=>c.id===excerptId).annotation.visible,false);
  await change('study.annotation.update',{cardId:excerptId,visible:true});
  s=await change('study.cards.batch',{cardIds:[a,b],patch:{favorite:true,addTags:['agent-complete']}});
  assert(s.cards.filter(c=>[a,b].includes(c.id)).every(c=>c.favorite&&c.tags.includes('agent-complete')));
  s=await change('study.cards.copy',{cardIds:[a],descendants:false});
  assert(s.lastCopy.cardIds[0]!==a);assert(s.cards.some(c=>c.id===s.lastCopy.cardIds[0]));
  await change('study.cards.organize',{cardIds:[excerptId],by:'toc'});
  s=await change('study.card.position',{cardId:a,x:900,y:250});
  assert.equal(s.cards.find(c=>c.id===a).position.x,900);
  await change('study.cards.sort',{by:'title',direction:'asc'});
  await change('study.submap.configure',{cardId:b,enabled:true,title:'Employee submap',open:true});
  s=await change('study.submap.open',{cardId:null});assert.equal(s.map.submapId,null);
  await change('study.submap.configure',{cardId:b,enabled:false});
  s=await change('study.summary.create',{cardIds:[a,b],title:'Cross-branch summary'});
  assert(s.cards.find(c=>c.title==='Cross-branch summary').summaryIds.includes(a));
  s=await change('study.card.split',{cardId:a,offsets:[10]});
  assert.equal(s.cards.find(c=>c.id===a).splitIds.length,2);
  const query=await api('study.board.query',{setId,filter:{tags:['agent-complete']},groupBy:['kind','tag'],limit:1});
  assert(query.total>=2&&query.nextOffset===1&&query.groups.length);
  s=await change('study.board.save',{title:'Employee smart board',filter:{tags:['agent-complete']},groupBy:['kind'],sort:'title'});
  const boardId=s.boards.find(x=>x.title==='Employee smart board').id;
  s=await change('study.board.materialize',{boardId,title:'Generated collection'});
  assert(s.cards.some(c=>c.boardSource===boardId));
  s=await change('study.board.remove',{boardId});assert(!s.boards.some(b=>b.id===boardId));
  s=await change('study.capture.settings',{color:'#3478a1',tags:['automatic'],inMap:true,organize:'document',annotationStyle:'box'});
  assert.equal(s.captureSettings.color,'#3478a1');
  s=await change('study.appearance.set',{branchStyle:'both',cardStyle:{width:260,height:200,fontSize:14},paper:'grid'});
  assert.equal(s.appearance.width,260);assert.equal(s.map.branchStyle,'both');
  const geometry=await api('study.map.geometry',{setId});
  assert(geometry.positions.some(p=>p.cardId===a)&&geometry.width>0);
  await deny('study.cards.batch',{setId,expectedRevision:s.revision,cardIds:[a,b],patch:{editedText:'Cannot overwrite a batch'}},'INVALID_PARAMS');
  const global=await api('study.workspace.query',{filter:{query:'concept'},groupBy:['study','kind'],limit:100});
  assert(global.cards.some(c=>c.ownerSetId===setId));
  s=await get();
  const globalEdit=await api('study.workspace.batch',{targets:[{setId,cardId:a}],expectedRevisions:{[setId]:s.revision},patch:{addTags:['global-board']}});
  assert.equal(globalEdit.updated,1);assert((await get()).cards.find(c=>c.id===a).tags.includes('global-board'));
  console.log('PASS Employee navigation, annotations, cards, submaps, smart boards and geometry');
};
