"use strict";
const assert = require('node:assert/strict');
exports.exercise = async ({api,get,change,setId,pdf,flow,editDoc}) => {
  let d=await editDoc('document.region.set',{page:1,start:.35,end:.5});
  const regionId=d.foldRegions.find(r=>r.start===.35).id;
  assert((await api('document.region.list',{id:d.id})).regions.some(r=>r.id===regionId));
  let layout=await api('document.layout.get',{id:d.id,page:1,width:612,setId});
  assert(layout.blocks.some(b=>b.type==='fold'));
  d=await editDoc('document.layout.undo');assert(!d.foldRegions.some(r=>r.id===regionId));
  d=await editDoc('document.layout.redo');assert(d.foldRegions.some(r=>r.id===regionId));
  d=await editDoc('document.region.remove',{regionId});assert(!d.foldRegions.some(r=>r.id===regionId));
  await editDoc('document.fold.chapters',{nodeIds:[pdf.toc[0].id],folded:true});
  await editDoc('document.fold.chapters',{nodeIds:[pdf.toc[0].id],folded:false});
  let s=await change('study.note.place',{documentId:pdf.id,expectedSourceVersion:pdf.sourceVersion,title:'In-page note',text:'**Persisted note**',locator:{page:1,pageOffset:.45},display:'embedded',height:120});
  assert(s.cards.find(c=>c.id===s.lastPlacedNote).anchor.display==='embedded');
  layout=await api('document.layout.get',{id:pdf.id,page:1,width:612,setId});
  assert(layout.blocks.some(b=>b.type==='note'));
  d=await editDoc('document.meta.update',{title:'Source with metadata',tags:['employee'],category:'Research',favorite:true});
  assert(d.favorite&&d.title==='Source with metadata');
  const pages=await api('document.pages.query',{id:d.id,setId,kind:'cards',limit:1});
  assert(pages.total>=1&&pages.pages[0].cards.length);
  const tabs=await api('reader.tabs.set',{ids:[flow.id,pdf.id],limit:20});assert.deepEqual(tabs.ids,[flow.id,pdf.id]);
  let saved=await api('reader.comparisons.save',{title:'Three independent panes',primary:{documentId:pdf.id,locator:{page:1}},panes:[{documentId:pdf.id,locator:{page:2}},{documentId:flow.id,locator:{section:0}}],direction:'columns',ratio:.5});
  assert(saved.panes.length===2);
  assert((await api('reader.comparisons.list')).views.some(v=>v.id===saved.id));
  assert((await api('reader.comparisons.open',{viewId:saved.id})).opened);
  saved=await api('reader.comparisons.update',{viewId:saved.id,expectedRevision:saved.revision,title:'Restored comparison'});
  assert.equal(saved.title,'Restored comparison');
  s=await get();
  const notebook=await api('reader.notebook.create',{sourceId:pdf.id,expectedSourceVersion:pdf.sourceVersion,path:'Books/employee-attached.pdf',paper:'dots',setId,expectedRevision:s.revision,activate:false});
  assert.equal((await api('reader.notebook.source',{id:notebook.id,page:2})).documentId,pdf.id);
  const unlinked=await api('reader.notebook.unlink',{id:notebook.id,expectedRevision:notebook.revision});assert(!unlinked.attachedTo);
  let outline=await api('toc.list',{id:flow.id});
  outline=await api('toc.batch',{id:flow.id,expectedRevision:outline.revision,operations:[{action:'add',title:'Batch chapter',locator:{section:0}}]});
  assert(outline.toc.some(c=>c.title==='Batch chapter'));
  outline=await api('toc.undo',{id:flow.id,expectedRevision:outline.revision});assert(!outline.toc.some(c=>c.title==='Batch chapter'));
  outline=await api('toc.redo',{id:flow.id,expectedRevision:outline.revision});assert(outline.toc.some(c=>c.title==='Batch chapter'));
  await api('toc.generate',{id:flow.id,expectedRevision:outline.revision,strategy:'original'});
  s=await change('study.toc.import',{documentId:flow.id});assert(s.cards.some(c=>c.outlineSource?.documentId===flow.id));
  let virtual=await api('document.virtual.create',{path:'Books/employee-virtual.mrv',pages:[{documentId:pdf.id,expectedSourceVersion:pdf.sourceVersion,page:2}],activate:false});
  assert.equal((await api('document.virtual.source',{id:virtual.id,page:1})).locator.page,2);
  virtual=await api('document.virtual.update',{id:virtual.id,expectedRevision:virtual.revision,action:'append',pages:[{blank:true,paper:'grid'}],activate:false});
  assert.equal(virtual.pageCount,2);
  virtual=await api('document.virtual.refresh',{id:virtual.id,expectedRevision:virtual.revision,activate:false});assert(!virtual.sourceChanged);
  const indexed=await api('library.index',{limit:100});assert(indexed.indexed.length>=2);
  const hits=await api('library.search',{query:'Shared AND CLI',kind:'documents'});assert(hits.total>=1);
  console.log('PASS Employee page folding, embedded notes, source tabs, comparisons, notebooks, virtual pages and search');
};
