import assert from 'node:assert/strict'
import fs from 'node:fs'
import {transformSync} from 'esbuild'
const source=new URL('../renderer/src/components/channel-post-model.ts',import.meta.url)
const {code}=transformSync(fs.readFileSync(source,'utf8'),{loader:'ts',format:'esm'})
const {ChannelPostSource,newestPosts,postPhotos,postExcerpt}=await import('data:text/javascript;base64,'+Buffer.from(code).toString('base64'))
const post=(id,plugin,sourceId,time=1)=>Object.freeze({id,plugin,sourceId,sourceName:'Same display name',authorName:'Author',publishedAt:time,media:Object.freeze([])})
const input=Object.freeze([post('a','x','one',1),post('b','x','two',3),post('c','youtube','one',3),post('d','telegram','one',2),post('e','x','one',2)])
const ordered=newestPosts(input),groups=ChannelPostSource.collect(ordered)
assert.deepEqual(input.map(item=>item.id),['a','b','c','d','e'],'never reorder live data')
assert.deepEqual(ordered.map(item=>item.id),['c','b','e','d','a'])
assert.equal(groups.length,4,'same names / IDs must not collapse different authors or platforms')
assert.ok(groups.every(group=>group instanceof ChannelPostSource))
assert.deepEqual(groups.find(group=>group.key==='x:one').posts.map(item=>item.id),['e','a'])
assert.equal(groups.find(group=>group.key==='telegram:one').platform,'telegram')
assert.deepEqual(ChannelPostSource.collect([]),[])
const media=Object.freeze([{id:'avatar',mimeType:'image/png'},{id:'cover',mimeType:'image/jpeg'},{id:'second',mimeType:'image/webp'},{id:'file',mimeType:'application/pdf'}].map(Object.freeze))
assert.deepEqual(postPhotos({media,avatarMediaId:'avatar'}).map(item=>item.id),['cover','second'])
assert.equal(postExcerpt('# A title\n\n**Read** [the original](https://example.invalid) ![remote](https://example.invalid/image.png)'),'A title Read the original')
assert.equal(postExcerpt(''), '')
assert.equal(postExcerpt('中文\n\n正文 👋'),'中文 正文 👋')
console.log('PASS channel post model: source identity, stable order, immutable input, local cover selection and text previews')
